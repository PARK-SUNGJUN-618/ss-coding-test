/*
 * 問題1：条件を満たす整数の合計
 *
 * 1以上100000以下の整数のうち、
 * 以下の条件をすべて満たす整数の合計を求めてください。
 *
 * 【条件】
 * 1. 4または7の倍数である。
 * 2. ただし、4と7の両方の倍数である整数は除外する。
 * 3. 各桁の数字の合計が3の倍数である。
 *
 * 【例】
 * 12 → 条件を満たす
 * 28 → 条件を満たさない
 * 21 → 条件を満たす
 * 16 → 条件を満たさない
 *
 * 【出力】
 * 条件を満たすすべての整数の合計を
 * 10進数の整数として出力してください。
 *
 * 【注意】
 * 外部ライブラリは使用しないでください。
 * Java 11の標準機能のみ使用できます。
 */


class Solution1 {
    public static void main(String[] args) {
        Long sum = (long) 0;
        for(int i = 1; i <= 100000; i++ ) {
            if (i % 4 == 0 || i % 7 == 0) {
                if (i % 28 != 0 && i % 3 == 0) {
                    sum += i;
                }
            }
        }

        System.out.println("sum=[" + sum + "]");
    }
}
