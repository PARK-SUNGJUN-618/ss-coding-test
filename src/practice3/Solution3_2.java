/*
【第2問】条件を満たす連続区間の数

長さ10000の整数配列 A があり、
各要素は以下の式で生成されます。

A[i] = (int)((i * 73L + 19) % 100) + 1;
（0 <= i < 10000）

この配列から、連続する3つの要素
A[i], A[i+1], A[i+2] を選びます。

以下の条件をすべて満たす区間の数を
求めてください。

【条件】
1. 3つの要素の合計が150以上である。
2. 3つの要素はすべて異なる。
3. 中央の要素 A[i+1] が、
   両端の要素 A[i], A[i+2] より大きい。

【制約】
・0 <= i <= 9997
・実行時間制限：2秒
・使用言語：Java

【解答形式】
条件を満たす区間の数を整数で回答してください。
*/

class Solution3_2 {
    public static void main(String[] args) {
        int[] A = new int[10000];

        for (int i = 0; i < A.length; i++) {
            A[i] = (int)((i * 73L + 19) % 100) + 1;
        }

        int count = 0;

        for (int i = 0; i < A.length - 2; i++) {
            if (A[i] + A[i+1] + A[i+2] >= 150) {
                if (A[i] != A[i+1] && A[i+1] != A[i+2] && A[i] != A[i+2]) {
                    if (A[i+1] > A[i] && A[i+1] > A[i+2]) {
                        count++;
                    }
                }
            }
        }

        System.out.println(count);
    }
}
