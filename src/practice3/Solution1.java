/*
【第1問】条件付き整数の総和

1以上100000以下の整数 x のうち、
以下の条件をすべて満たす整数の総和を求めてください。

【条件】
1. x は 4 または 7 の倍数である。
2. x は 5 の倍数ではない。
3. x の各桁の数字の和は 3 の倍数である。

【出力】
条件をすべて満たす整数 x の総和を出力してください。

【制約】
・1 <= x <= 100000
・実行時間制限：2秒
・使用言語：Java

【解答形式】
求めた総和を整数で回答してください。

【注意】
・解答コードを提出する必要はありません。
・計算結果の数値のみを回答してください。
*/

class Solution1 {
    public static void main(String[] args) {
        long sum = 0;

        for (int i = 1; i <= 100000; i++) {
            if (i % 4 == 0 || i % 7 == 0) {
                if (i % 5 != 0) {
                    if (i % 3 == 0) {
                        sum += i;
                    }
                }
            }
        }

        System.out.println(sum);
    }
}
